
const mongoose = require("mongoose");
const { randomBytes } = require("node:crypto");

const { Schema } = mongoose;

// ================== ENQUIRY ID ==================
// Generate a unique enquiry reference on the server.
function generateEnquiryId() {
    return `ENQ-${randomBytes(8).toString("hex").toUpperCase()}`;
}

// ================== CONTACT ENQUIRY SCHEMA ==================
const contactSchema = new Schema(
    {
        // ================== ENQUIRY REFERENCE ==================
        enquiryId: {
            type: String,
            required: true,
            unique: true,
            immutable: true,
            default: generateEnquiryId,
        },

        // ================== SENDER DETAILS ==================
        name: {
            type: String,
            required: true,
            trim: true,
            minlength: 2,
            maxlength: 100,
        },

        email: {
            type: String,
            required: true,
            trim: true,
            lowercase: true,
            maxlength: 254,
        },

        phone: {
            type: String,
            required: true,
            trim: true,
            maxlength: 10,
            validate: {
                validator(value) {
                    return /^[6-9]\d{9}$/.test(value);
                },
                message: "Enter a valid 10-digit Indian mobile number.",
            },
        },

        // ================== ENQUIRY DETAILS ==================
        subject: {
            type: String,
            required: true,
            trim: true,
            minlength: 1,
            maxlength: 150,
        },

        message: {
            type: String,
            required: true,
            trim: true,
            minlength: 1,
            maxlength: 3000,
        },

        // ================== SUBMISSION DATE ==================
        // Automatically generated by the backend.
        submittedAt: {
            type: Date,
            required: true,
            immutable: true,
            default: Date.now,
        },
    },
    {
        timestamps: true,

        // Remove Mongoose version from API JSON responses.
        toJSON: {
            transform(doc, result) {
                delete result.__v;
                return result;
            },
        },
    }
);

// ================== DATABASE INDEX ==================
// Support newest-first enquiry listing and pagination.
contactSchema.index({ submittedAt: -1, _id: -1 });

// ================== MODEL ==================
const Contact = mongoose.model("Contact", contactSchema);

// ================== EXPORT ==================
module.exports = Contact;
